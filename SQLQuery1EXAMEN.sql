CREATE TRIGGER CT_APJ_INSERTAR_PROFESOR
ON APJ_PROFESOR_BASE
FOR INSERT
AS
INSERT APJ_PROFESOR_INTERNO(APJ_PROFESOR_INTERNO.RFC,
APJ_PROFESOR_INTERNO.NOM_PROF, APJ_PROFESOR_INTERNO.ACADEMINA)
SELECT inserted.RFC, inserted.NOM_PROF, inserted.ACADEMIA);

