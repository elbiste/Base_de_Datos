CREATE VIEW APJ_SALONES_ALUMNO_PROFESOR AS(
SELECT SALON, NOM_ALUMNO, NOM_PROF
FROM APJ_GRUPO
INNER JOIN APJ_ALUMNO_GRUPO ON ID_GRUPO= GRUPO
INNER JOIN APJ_ALUMNO ON APJ_ALUMNO_GRUPO.GRUPO= APJ_ALUMNO.BOLETA
INNER JOIN APJ_PROFESOR_BASE ON  APJ_GRUPO.CVE_PROFESOR= APJ_PROFESOR_BASE.RFC
);

SELECT * FROM APJ_SALONES_ALUMNO_PROFESOR;

